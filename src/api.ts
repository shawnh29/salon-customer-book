import type { Customer, CustomerListResponse } from "./types";
import type { CustomerInput, FieldErrors } from "./shared/customer";

export class ApiError extends Error {
  constructor(
    message: string,
    public status: number,
    public fieldErrors?: FieldErrors,
  ) {
    super(message);
  }
}

export function isAbortError(err: unknown): boolean {
  return err instanceof DOMException && err.name === "AbortError";
}

async function request<T>(url: string, init?: RequestInit): Promise<T> {
  let res: Response;
  try {
    res = await fetch(url, init);
  } catch (err) {
    if (isAbortError(err)) throw err;
    throw new ApiError("Could not reach the server. Check your internet connection and try again.", 0);
  }

  if (res.status === 204) return undefined as T;

  const data = (await res.json().catch(() => null)) as
    | { error?: string; fieldErrors?: FieldErrors }
    | null;

  if (!res.ok) {
    throw new ApiError(data?.error ?? `Something went wrong (error ${res.status}).`, res.status, data?.fieldErrors);
  }
  return data as T;
}

const JSON_HEADERS = { "Content-Type": "application/json" };

export function listCustomers(q: string, signal?: AbortSignal): Promise<CustomerListResponse> {
  const qs = q ? `?q=${encodeURIComponent(q)}` : "";
  return request<CustomerListResponse>(`/api/customers${qs}`, { signal });
}

export function getCustomer(id: string): Promise<Customer> {
  return request<Customer>(`/api/customers/${encodeURIComponent(id)}`);
}

export function createCustomer(input: CustomerInput): Promise<Customer> {
  return request<Customer>("/api/customers", {
    method: "POST",
    headers: JSON_HEADERS,
    body: JSON.stringify(input),
  });
}

export function updateCustomer(id: string, input: CustomerInput): Promise<Customer> {
  return request<Customer>(`/api/customers/${encodeURIComponent(id)}`, {
    method: "PUT",
    headers: JSON_HEADERS,
    body: JSON.stringify(input),
  });
}

export function deleteCustomer(id: string): Promise<void> {
  return request<void>(`/api/customers/${encodeURIComponent(id)}`, { method: "DELETE" });
}

function localDateStamp(): string {
  const d = new Date();
  const mm = String(d.getMonth() + 1).padStart(2, "0");
  const dd = String(d.getDate()).padStart(2, "0");
  return `${d.getFullYear()}-${mm}-${dd}`;
}

/** Downloads the CSV generated by the server from the real database. */
export async function downloadCsv(): Promise<void> {
  let res: Response;
  try {
    res = await fetch("/api/export");
  } catch {
    throw new ApiError("Could not reach the server. Check your internet connection and try again.", 0);
  }
  if (!res.ok) throw new ApiError("The export failed. Please try again.", res.status);

  const blob = await res.blob();
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = `salon-customers-${localDateStamp()}.csv`;
  document.body.appendChild(a);
  a.click();
  a.remove();
  URL.revokeObjectURL(url);
}
